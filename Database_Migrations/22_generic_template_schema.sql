--                         missing columns to existing tables - the drift check lists those.
--                         Then, if the database still holds the old AI-SEO tables, run 24_remove_ai_seo_tables.sql LAST
--                         (destructive - take a backup).
--   * One transaction: if any statement fails nothing is applied.
