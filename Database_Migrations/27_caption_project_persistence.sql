-- ============================================================
-- Migration 27: Captain Title - saved projects: resume, autosave, restore points
--
-- WHAT IT DOES
--   1. Adds to "CaptionProjects":
--        "ThumbnailPath"     library thumbnail (NULL on older projects: the library shows a placeholder)
--        "Revision"          optimistic-concurrency version of the editable content
--        "RenderedRevision"  the Revision the stored export was made from (export is current when they match)
--        "LastEditedAt"      library sort key (back-filled from UpdatedAt / CreatedAt)
--        "CreditConsumedAt"  when the project's credit was settled (back-filled for every project that ever finished)
--   2. Creates "CaptionProjectEditorStates": one row per project with where the user left off (playhead, tabs) as JSON.
--   3. Creates "CaptionProjectVersions": JSON restore points of the editable document.
--   4. Adds the index behind the project library.
--
-- PREREQUISITES: 22 -> 21 -> 25 -> 26 already applied.
-- RUN ORDER:     ... 21 -> 25 -> 26 -> 27.   Run it BEFORE deploying the application build that contains this change
--                (the build reads these columns; the previous build keeps working with them in place).
-- IDEMPOTENT:    yes - safe to run again. Back-fills only touch rows that have not been filled yet.
-- DESTRUCTIVE:   no. Nothing is dropped or deleted. Existing project content is not modified.
-- LOCKS:         the ALTER and UPDATE take a short lock on "CaptionProjects"; the UPDATE touches every row once, so prefer a quiet moment.
--                On a very large table build the index separately with CREATE INDEX CONCURRENTLY (outside BEGIN/COMMIT).
-- ROLLBACK:      deploy the previous build first, then:
--                  DROP TABLE IF EXISTS "CaptionProjectVersions", "CaptionProjectEditorStates";
--                  DROP INDEX IF EXISTS "IX_CaptionProjects_UserId_LastEditedAt_Id";
--                  ALTER TABLE "CaptionProjects" DROP COLUMN IF EXISTS "ThumbnailPath", DROP COLUMN IF EXISTS "Revision",
--                    DROP COLUMN IF EXISTS "RenderedRevision", DROP COLUMN IF EXISTS "LastEditedAt", DROP COLUMN IF EXISTS "CreditConsumedAt";
--                Back up first: dropping these loses restore points and saved editor positions.
--
-- READ-ONLY CHECKS: see the SELECTs at the very bottom of this file (safe to run any time).
-- ============================================================

BEGIN;

-- 1. new project columns ---------------------------------------------------------------------------
ALTER TABLE "CaptionProjects"
    ADD COLUMN IF NOT EXISTS "ThumbnailPath"    VARCHAR(500) NULL,
    ADD COLUMN IF NOT EXISTS "Revision"         INTEGER      NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS "RenderedRevision" INTEGER      NULL,
    ADD COLUMN IF NOT EXISTS "LastEditedAt"     TIMESTAMPTZ  NULL,
    ADD COLUMN IF NOT EXISTS "CreditConsumedAt" TIMESTAMPTZ  NULL;

-- LastEditedAt starts nullable so the back-fill can tell "not filled yet" apart, then becomes required.
UPDATE "CaptionProjects" SET "LastEditedAt" = COALESCE("UpdatedAt", "CreatedAt") WHERE "LastEditedAt" IS NULL;
ALTER TABLE "CaptionProjects" ALTER COLUMN "LastEditedAt" SET DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE "CaptionProjects" ALTER COLUMN "LastEditedAt" SET NOT NULL;

-- An existing export is current: the previous build never tracked edits made after it.
UPDATE "CaptionProjects" SET "RenderedRevision" = "Revision"
 WHERE "Status" = 'rendered' AND "RenderPath" IS NOT NULL AND "RenderedRevision" IS NULL;

-- A credit was charged once a run completed; TranscriptionMode is only written by a completed run and survives a later re-listen.
-- Without this a re-listen of an older project would be charged a second time.
UPDATE "CaptionProjects" SET "CreditConsumedAt" = COALESCE("UpdatedAt", "CreatedAt")
 WHERE "CreditConsumedAt" IS NULL AND ("TranscriptionMode" IS NOT NULL OR "Status" IN ('ready','rendering','rendered'));

-- 2. where the user left off -----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "CaptionProjectEditorStates" (
    "ProjectId" INTEGER     NOT NULL PRIMARY KEY REFERENCES "CaptionProjects"("Id") ON DELETE CASCADE,
    "StateJson" JSONB       NOT NULL DEFAULT '{}',
    "UpdatedAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. restore points --------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "CaptionProjectVersions" (
    "Id"              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProjectId"       INTEGER     NOT NULL REFERENCES "CaptionProjects"("Id") ON DELETE CASCADE,
    "ProjectRevision" INTEGER     NOT NULL,
    "Reason"          VARCHAR(30) NOT NULL,
    "DocumentJson"    JSONB       NOT NULL,
    "CreatedAt"       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. indexes ---------------------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS "IX_CaptionProjects_UserId_LastEditedAt_Id"
    ON "CaptionProjects" ("UserId", "LastEditedAt" DESC, "Id" DESC);
CREATE INDEX IF NOT EXISTS "IX_CaptionProjectVersions_ProjectId_Id"
    ON "CaptionProjectVersions" ("ProjectId", "Id" DESC);

COMMIT;

-- ============================================================
-- READ-ONLY CHECKS (safe to run any time, before or after)
-- ============================================================
-- new columns present? (expect 5 rows)
SELECT column_name, data_type, is_nullable FROM information_schema.columns
 WHERE table_name = 'CaptionProjects'
   AND column_name IN ('ThumbnailPath','Revision','RenderedRevision','LastEditedAt','CreditConsumedAt')
 ORDER BY column_name;
-- new tables present? (expect 2 rows)
SELECT table_name FROM information_schema.tables
 WHERE table_name IN ('CaptionProjectEditorStates','CaptionProjectVersions') ORDER BY table_name;
-- projects by status and credit state
SELECT "Status", "CreditConsumedAt" IS NOT NULL AS credit_settled, COUNT(*) FROM "CaptionProjects" GROUP BY 1, 2 ORDER BY 1, 2;
