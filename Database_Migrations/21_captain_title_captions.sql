-- ============================================================
-- Migration 21: Captain Title - caption generator module
-- Source: port of the old FastAPI/MongoDB project (collections users/projects/usage/payment_transactions)
-- Idempotent: safe to run more than once (CREATE ... IF NOT EXISTS, seed rows use ON CONFLICT DO NOTHING so admin edits survive).
-- Includes the factory catalog (themes, fonts, variants, SFX, stickers, filler words, plans), the "captions.*" SystemSetting rows
-- and the two LlmJobConfigs rows. The application never writes schema or seed data itself - run this script manually.
-- REQUIRES: 22_generic_template_schema.sql first ("User", "SystemSetting", "LlmJobConfigs" must exist).
-- Users/auth/sessions are NOT migrated: the template's "User"/RefreshToken tables replace the old Mongo users/user_sessions.
-- ============================================================

CREATE TABLE IF NOT EXISTS "CaptionProjects" (
    "Id"                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"                   INTEGER NOT NULL REFERENCES "User"("Id") ON DELETE CASCADE,
    "Name"                     VARCHAR(255) NOT NULL,
    "Duration"                 DOUBLE PRECISION NOT NULL DEFAULT 0,
    "Width"                    INTEGER NULL,
    "Height"                   INTEGER NULL,
    "SizeBytes"                BIGINT NOT NULL DEFAULT 0,
    "Theme"                    VARCHAR(50) NOT NULL DEFAULT 'viral',
    "FontId"                   VARCHAR(50) NOT NULL DEFAULT 'poppins',
    "WordsPerCaption"          INTEGER NULL,
    "CaptionLines"             INTEGER NOT NULL DEFAULT 1,
    "CaptionPosition"          VARCHAR(10) NOT NULL DEFAULT 'bottom',
    "AudioVolume"              INTEGER NOT NULL DEFAULT 100,
    "AudioMuted"               BOOLEAN NOT NULL DEFAULT FALSE,
    "Brightness"               INTEGER NOT NULL DEFAULT 0,
    "Contrast"                 INTEGER NOT NULL DEFAULT 100,
    "Saturation"               INTEGER NOT NULL DEFAULT 100,
    "RenderQuality"            VARCHAR(10) NOT NULL DEFAULT 'high',
    "Variant"                  VARCHAR(50) NULL,
    "WordsJson"                JSONB NOT NULL DEFAULT '[]',
    "ElementsJson"             JSONB NOT NULL DEFAULT '[]',
    "SfxMarkersJson"           JSONB NOT NULL DEFAULT '[]',
    "SourceTranscript"         TEXT NOT NULL DEFAULT '',
    "SpeechLanguage"           VARCHAR(10) NOT NULL DEFAULT 'auto',
    "TranscriptionMode"        VARCHAR(60) NULL,
    "TranscriptionQualityJson" JSONB NULL,
    "SourcePath"               VARCHAR(500) NOT NULL,
    "PreviewPath"              VARCHAR(500) NULL,
    "PreviewContentType"       VARCHAR(100) NULL,
    "ContentType"              VARCHAR(100) NULL,
    "CreditType"               VARCHAR(20) NULL,
    "RenderPath"               VARCHAR(500) NULL,
    "Status"                   VARCHAR(20) NOT NULL DEFAULT 'queued',
    "Progress"                 INTEGER NOT NULL DEFAULT 5,
    "ProcessingLabel"          VARCHAR(100) NOT NULL DEFAULT 'Upload complete',
    "ErrorMessage"             VARCHAR(500) NULL,
    "CreatedAt"                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"                TIMESTAMPTZ NULL
);
CREATE INDEX IF NOT EXISTS "IX_CaptionProjects_UserId_CreatedAt" ON "CaptionProjects"("UserId", "CreatedAt");
CREATE INDEX IF NOT EXISTS "IX_CaptionProjects_Status" ON "CaptionProjects"("Status");

CREATE TABLE IF NOT EXISTS "CaptionUsages" (
    "Id"                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"                INTEGER NOT NULL REFERENCES "User"("Id") ON DELETE CASCADE,
    "FreeRemaining"         INTEGER NOT NULL DEFAULT 0,
    "OneoffCredits"         INTEGER NOT NULL DEFAULT 0,
    "OneoffPurchaseCount"   INTEGER NOT NULL DEFAULT 0,
    "BasicCredits"          INTEGER NOT NULL DEFAULT 0,
    "SubscriptionActive"    BOOLEAN NOT NULL DEFAULT FALSE,
    "VideosCreated"         INTEGER NOT NULL DEFAULT 0,
    "UpdatedAt"             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionUsages_UserId" ON "CaptionUsages"("UserId");

CREATE TABLE IF NOT EXISTS "CaptionPaymentTransactions" (
    "Id"            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"        INTEGER NOT NULL,
    "SessionId"     VARCHAR(255) NOT NULL,
    "PackageId"     VARCHAR(50) NOT NULL,
    "Status"        VARCHAR(20) NOT NULL DEFAULT 'initiated',
    "PaymentStatus" VARCHAR(20) NOT NULL DEFAULT 'pending',
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"     TIMESTAMPTZ NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionPaymentTransactions_SessionId" ON "CaptionPaymentTransactions"("SessionId");
CREATE INDEX IF NOT EXISTS "IX_CaptionPaymentTransactions_UserId" ON "CaptionPaymentTransactions"("UserId");

CREATE TABLE IF NOT EXISTS "CaptionThemes" (
    "Id"          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Key"         VARCHAR(50) NOT NULL,
    "Name"        VARCHAR(100) NOT NULL,
    "BaseColor"   VARCHAR(9) NULL,
    "AccentColor" VARCHAR(9) NOT NULL,
    "AccentFont"  VARCHAR(100) NULL,
    "TiersJson"   JSONB NULL,
    "CardJson"    JSONB NULL,
    "IsActive"    BOOLEAN NOT NULL DEFAULT TRUE,
    "SortOrder"   INTEGER NOT NULL DEFAULT 0,
    "CreatedAt"   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionThemes_Key" ON "CaptionThemes"("Key");

CREATE TABLE IF NOT EXISTS "CaptionFonts" (
    "Id"        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Key"       VARCHAR(50) NOT NULL,
    "Label"     VARCHAR(100) NOT NULL,
    "Family"    VARCHAR(100) NOT NULL,
    "IsActive"  BOOLEAN NOT NULL DEFAULT TRUE,
    "SortOrder" INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionFonts_Key" ON "CaptionFonts"("Key");

CREATE TABLE IF NOT EXISTS "CaptionVariants" (
    "Id"            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Key"           VARCHAR(50) NOT NULL,
    "Label"         VARCHAR(100) NOT NULL,
    "FontFamily"    VARCHAR(100) NOT NULL,
    "Border"        INTEGER NOT NULL DEFAULT 0,
    "OutlineColor"  VARCHAR(9) NULL,
    "Shadow"        INTEGER NOT NULL DEFAULT 0,
    "Blur"          INTEGER NOT NULL DEFAULT 0,
    "AccentColor"   VARCHAR(9) NOT NULL,
    "CssTextShadow" VARCHAR(300) NULL,
    "CssStroke"     VARCHAR(50) NULL,
    "IsActive"      BOOLEAN NOT NULL DEFAULT TRUE,
    "SortOrder"     INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionVariants_Key" ON "CaptionVariants"("Key");

CREATE TABLE IF NOT EXISTS "CaptionSfxTypes" (
    "Id"              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Key"             VARCHAR(50) NOT NULL,
    "Label"           VARCHAR(100) NOT NULL,
    "Icon"            VARCHAR(50) NOT NULL DEFAULT 'volume',
    "Color"           VARCHAR(9) NOT NULL DEFAULT '#FFFFFF',
    "PreviewKind"     VARCHAR(20) NOT NULL DEFAULT 'blip',
    "Frequency"       DOUBLE PRECISION NOT NULL DEFAULT 0,
    "SweepTo"         DOUBLE PRECISION NOT NULL DEFAULT 0,
    "DurationSeconds" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "IsActive"        BOOLEAN NOT NULL DEFAULT TRUE,
    "SortOrder"       INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionSfxTypes_Key" ON "CaptionSfxTypes"("Key");

CREATE TABLE IF NOT EXISTS "CaptionStickers" (
    "Id"        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Glyph"     VARCHAR(20) NOT NULL,
    "IsActive"  BOOLEAN NOT NULL DEFAULT TRUE,
    "SortOrder" INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionStickers_Glyph" ON "CaptionStickers"("Glyph");

CREATE TABLE IF NOT EXISTS "CaptionPlans" (
    "Id"                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Key"                 VARCHAR(50) NOT NULL,
    "Name"                VARCHAR(100) NOT NULL,
    "Kind"                VARCHAR(20) NOT NULL DEFAULT 'payment',
    "Price"               NUMERIC(10,2) NOT NULL DEFAULT 0,
    "Currency"            VARCHAR(3) NOT NULL DEFAULT 'INR',
    "Videos"              INTEGER NOT NULL DEFAULT 0,
    "MaxSeconds"          INTEGER NOT NULL DEFAULT 0,
    "MaxPurchasesPerUser" INTEGER NULL,
    "StripeLookupKey"     VARCHAR(100) NULL,
    "Description"         VARCHAR(200) NULL,
    "IsFeatured"          BOOLEAN NOT NULL DEFAULT FALSE,
    "IsActive"            BOOLEAN NOT NULL DEFAULT TRUE,
    "SortOrder"           INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionPlans_Key" ON "CaptionPlans"("Key");

CREATE TABLE IF NOT EXISTS "CaptionFillerWords" (
    "Id"       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Word"     VARCHAR(50) NOT NULL,
    "IsActive" BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_CaptionFillerWords_Word" ON "CaptionFillerWords"("Word");

